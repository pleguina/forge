"""VHDL entity around the structural Verilog top level.

``gen-top --mode vhdl`` writes the Verilog top under ``<top>_core`` and this
entity, named ``<top>``, with the same ports: VHDL code such as an EMP
payload instantiates it like any VHDL entity, and Vivado elaborates the
mixed-language design. There is one structural generator, so the VHDL top
has every register stage, crossing and synchronizer the Verilog one has.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, Iterable, List

# IEEE 1076-2008 reserved words.
_RESERVED = frozenset("""
abs access after alias all and architecture array assert assume assume_guarantee attribute
begin block body buffer bus case component configuration constant context cover default
disconnect downto else elsif end entity exit fairness file for force function generate generic
group guarded if impure in inertial inout is label library linkage literal loop map mod nand
new next nor not null of on open or others out package parameter port postponed procedure
process property protected pure range record register reject release rem report restrict
restrict_guarantee return rol ror select sequence severity shared signal sla sll sra srl strong
subtype then to transport type unaffected units until use variable vmode vprop vunit wait when
while with xnor xor
""".split())
_BASIC_IDENTIFIER = re.compile(r"^[A-Za-z](?:_?[A-Za-z0-9])*$")


def _vhdl_type(width: int) -> str:
    return "std_logic" if width == 1 else f"std_logic_vector({width - 1} downto 0)"


def _check_names(names: Iterable[str]) -> None:
    """A port binds to the Verilog one by name, and VHDL ignores case."""
    bad = [n for n in names if not _BASIC_IDENTIFIER.match(n) or n.lower() in _RESERVED]
    if bad:
        raise ValueError(
            "these top-level ports are not VHDL identifiers, so a VHDL entity cannot bind "
            f"them to the Verilog top: {', '.join(sorted(bad))}"
        )
    seen: Dict[str, str] = {}
    clashes = []
    for name in names:
        other = seen.setdefault(name.lower(), name)
        if other != name:
            clashes.append(f"{other}/{name}")
    if clashes:
        raise ValueError(
            "these top-level ports differ only in case, which VHDL does not distinguish: "
            + ", ".join(clashes)
        )


def write_vhdl_wrapper(
    top_ports: List[Dict[str, Any]], *, entity_name: str, core_name: str, out_path: Path,
) -> None:
    """Write entity *entity_name* instantiating Verilog module *core_name*.

    *top_ports* is the structural generator's own resolved port list
    (``name``, ``direction`` ``in``/``out``, ``width``).
    """
    names = [p["name"] for p in top_ports]
    _check_names([entity_name, core_name, *names])

    declarations = [
        f"{p['name']} : {'in' if p['direction'] == 'in' else 'out'} {_vhdl_type(int(p['width']))}"
        for p in top_ports
    ]

    def port_clause(indent: str) -> List[str]:
        if not declarations:
            return []
        body = (";\n" + indent + "  ").join(declarations)
        return [f"{indent}port (", f"{indent}  {body}", f"{indent});"]

    lines = [
        "-- Generated by forge gen-top --mode vhdl; do not edit.",
        f"-- {entity_name} instantiates the structural Verilog top {core_name} ({core_name}.v).",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "",
        f"entity {entity_name} is",
        *port_clause("  "),
        f"end entity {entity_name};",
        "",
        f"architecture wrapper of {entity_name} is",
        f"  component {core_name} is",
        *port_clause("    "),
        "  end component;",
        "begin",
        f"  core : {core_name}",
    ]
    if names:
        maps = ",\n".join(f"      {n} => {n}" for n in names)
        lines += ["    port map (", maps, "    );"]
    else:
        lines[-1] += ";"
    lines += ["end architecture wrapper;", ""]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
