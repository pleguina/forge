def _yaml_nullable(value: Any) -> str:
    """Return YAML representation for a potentially-null value."""
    if value is None or value == "" or value == "~":
        return "~"
    return str(value)


def _yaml_bool(value: bool) -> str:
    return "true" if value else "false"


def _yaml_list_block(key: str, values: list[str], indent: str = "  ") -> str:
    if not values:
        return ""
    lines = [f"{indent}{key}:"]
    lines.extend(f"{indent}  - {v}" for v in values)
    return "\n".join(lines) + "\n"


def _checker_args_block(args: list[str]) -> str:
    if not args:
        return ""
    lines = ["  args:"]
    lines.extend(f'    - "{a}"' for a in args)
    return "\n".join(lines)


def _xsim_extra_sources_block(extra_sources: list[tuple[str, str]]) -> str:
    if not extra_sources:
        return ""
    lines = ["  extra_sources:"]
    for path, lang in extra_sources:
        lines.append(f"    - path: {path}")
        lines.append(f"      lang: {lang}")
    return "\n".join(lines) + "\n"


def _render_checker_section(checker: Any, checker_mode: str, top_module: str) -> str:
    observed = getattr(checker, "observed_log", None) or f"xsim_work/{top_module}_outputs.csv"
    lines = [
        "checker:",
        f"  mode:           {getattr(checker, 'mode', None) or checker_mode}",
        f"  tool:           {getattr(checker, 'tool', None) or 'algo_top_xsim_checker'}",
        f"  binary:         {_yaml_nullable(getattr(checker, 'binary', None))}",
        f"  observed_log:   {observed}",
        f"  latency_cycles: {getattr(checker, 'latency_cycles', 0) or 0}",
        f"  tolerance:      {getattr(checker, 'tolerance', 0) or 0}",
        f"  pass_condition: {getattr(checker, 'pass_condition', None) or 'zero_mismatches'}",
    ]
    args = list(getattr(checker, "args", ()) or [])
    if args:
        lines.append("  args:")
        lines.extend(f'    - "{a}"' for a in args)
    return "\n".join(lines) + "\n"


def _render_xsim_section(xsim: Any) -> str:
    lines = [
        "xsim:",
        f"  use_sv_flag: {_yaml_bool(bool(getattr(xsim, 'use_sv_flag', True)))}",
        f"  top_lib: {_yaml_nullable(getattr(xsim, 'top_lib', None))}",
    ]
    extra_top_modules = list(getattr(xsim, "extra_top_modules", ()) or [])
    if extra_top_modules:
        lines.append("  extra_top_modules:")
        lines.extend(f"    - {v}" for v in extra_top_modules)
    elab_libs = list(getattr(xsim, "elab_libs", ()) or [])
    if elab_libs:
        lines.append("  elab_libs:")
        lines.extend(f"    - {v}" for v in elab_libs)
    extra_sources = list(getattr(xsim, "extra_sources", ()) or [])
    if extra_sources:
        lines.append("  extra_sources:")
        for src in extra_sources:
            lines.append(f"    - path: {src.path}")
            lines.append(f"      lang: {src.lang}")
    return "\n".join(lines) + "\n"


def generate_verify_flow_yml(
    flow_decl: Any,
    defaults: Any,
    output_path: Path,
    consumer_root: Path,
    plugin_id: "str" = "",
    dut_rtl: "str | None" = None,
    dut_manifest: "str | None" = None,
    dut_port_map: "str | None" = None,
    dut_tb_bindings: "str | None" = None,
    dut_port_signature: "str | None" = None,
    dataset_xml: "str | None" = None,
    dataset_parts_glob: "str | None" = None,
    dataset_parts: "tuple[str, ...]" = (),
    extra_simulation_fields: tuple = (),  # (key, value) pairs from plugin defaults
    source_path: "str" = "design.verification.yml",
) -> Path:
    """Generate a ``verify.flow.yml`` from a ``FlowDeclaration`` and defaults.

    Parameters
    ----------
    flow_decl:
        A ``FlowDeclaration`` dataclass instance from ``design_contract``.
    defaults:
        A ``SimulationDefaults`` dataclass instance for timing fallbacks.
    output_path:
        Absolute path where the ``verify.flow.yml`` should be written.
    consumer_root:
        Repo root used to make paths relative in the generated file.
    dut_rtl, dut_manifest, dut_port_map, dut_tb_bindings, dut_port_signature:
        Resolved DUT artifact paths, expressed relative to ``consumer_root``.
        Pass ``None`` for fields not relevant to the flow kind.
    dataset_xml:
        Resolved dataset XML path relative to ``consumer_root``.
    source_path:
        Informational: path of the source ``design.verification.yml`` shown
        in the generated file header comment.

    Returns
    -------
    Path to the written file.
    """
    # Resolve per-flow simulation values, falling back to contract defaults.
    clk   = getattr(defaults, "clk_period_ns", 4.0)
    rst   = getattr(flow_decl, "reset_cycles",               None) or getattr(defaults, "reset_cycles", 4)
    idle  = getattr(flow_decl, "idle_cycles_after_reset",    None) or getattr(defaults, "idle_cycles_after_reset", 0)
    drain = getattr(flow_decl, "post_stimulus_drain_cycles", None) or getattr(defaults, "post_stimulus_drain_cycles", 8)
    # Extra plugin-specific simulation fields passed through verbatim
    _extra = extra_simulation_fields or getattr(defaults, "extra", ())
    extra_sim_text = "".join(f"  {k}: {v}\n" for k, v in _extra) if _extra else ""

    checker = getattr(flow_decl, "checker", None)
    checker_mode = getattr(flow_decl, "checker_mode", "log_scan")
    if checker is not None and any(
        getattr(checker, f, None) is not None
        for f in ("binary", "observed_log", "latency_cycles", "tolerance", "pass_condition")
    ):
        checker_text = _render_checker_section(checker, checker_mode, flow_decl.top_module)
    else:
        checker_text = ""

    xsim = getattr(flow_decl, "xsim", None)
    if xsim is not None:
        xsim_text = _render_xsim_section(xsim)
    else:
        xsim_text = ""

    text = _FLOW_YML_TEMPLATE.format(
        flow_name=flow_decl.name,
        plugin=plugin_id or getattr(flow_decl, "_plugin", ""),
        kind=flow_decl.kind,
        backend=flow_decl.backend,
        top_module=flow_decl.top_module,
        tb_module=flow_decl.tb_module,
        dut_rtl=_yaml_nullable(dut_rtl),
        dut_manifest=_yaml_nullable(dut_manifest),
        dut_port_map=_yaml_nullable(dut_port_map),
        dut_tb_bindings=_yaml_nullable(dut_tb_bindings),
        dut_port_signature=_yaml_nullable(dut_port_signature),
        dataset_xml=_yaml_nullable(dataset_xml),
        dataset_parts_text=_render_dataset_parts(dataset_parts_glob, dataset_parts),
        default_event_id=getattr(flow_decl, "default_event_id", 1),
        clk_period_ns=clk,
        reset_cycles=rst,
        idle_cycles_after_reset=idle,
        post_stimulus_drain_cycles=drain,
        extra_sim_text=extra_sim_text,
        checker_mode=checker_mode,
        stimulus_mode=getattr(flow_decl, "stimulus_mode", "svh_include"),
        xsim_section=xsim_text,
        checker_section=checker_text,
        source_path=str(source_path),
    )

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(text)
    return output_path


def _render_dataset_parts(parts_glob: str | None, parts: tuple[str, ...]) -> str:
    lines: list[str] = []
    if parts_glob:
        lines.append(f"  parts_glob:       {parts_glob}")
    if parts:
        lines.append("  parts:")
        lines.extend(f"    - {part}" for part in parts)
    return ("\n".join(lines) + "\n") if lines else ""
