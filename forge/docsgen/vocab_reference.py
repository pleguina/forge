def real_transformation_kinds_in_source() -> "set[str]":
    """The transformation kinds actually constructed in
    ``forge/ir/build.py`` right now, found via a structural AST scan (not
    a text grep) — see ``_ast_utils.find_call_kwarg_string_values``."""
    return find_call_kwarg_string_values(
        _IR_BUILD_SOURCE, {"ResolvedTransformation"}, "kind",
    )


def check_transformation_registry_matches_source() -> "list[str]":
    """Return a list of human-readable problems, empty if the registry
    and the real emission sites in ``forge/ir/build.py`` agree exactly:
    every kind actually constructed is registered as ``"real"``, and no
    kind registered as ``"real"`` is missing from the source."""
    problems: "list[str]" = []
    real_in_source = real_transformation_kinds_in_source()
    registered_real = {
        k for k, d in TRANSFORMATION_KINDS.items() if d.status == "real"
    }

    for kind in sorted(real_in_source - registered_real):
        problems.append(
            f"kind {kind!r} is constructed in forge/ir/build.py but missing "
            f"from TRANSFORMATION_KINDS (or marked non-'real')"
        )
    for kind in sorted(registered_real - real_in_source):
        problems.append(
            f"kind {kind!r} is registered as 'real' but no construction site "
            f"was found in forge/ir/build.py — demote to 'reserved' or fix "
            f"the registry"
        )
    return problems


def generate_transformations_page() -> str:
    problems = check_transformation_registry_matches_source()
    if problems:
        raise RuntimeError(
            "TRANSFORMATION_KINDS registry is out of sync with "
            "forge/ir/build.py:\n  " + "\n  ".join(problems)
        )

    lines = [
        "# Transformations",
        "",
        "<!-- Generated by `python -m forge.docsgen`. Do not edit directly. -->",
        "",
        "The transformation-kind vocabulary (`forge.ir.model.ResolvedTransformation`)",
        "isn't backed by a live registry in the source — this page is",
        "generated from a small, AST-verified registry in",
        "`forge.docsgen.vocab_reference` that is checked, at generation",
        "time, against every real `ResolvedTransformation(kind=...)`",
        "construction site in `forge/ir/build.py` (structurally, via AST,",
        "not a text grep) — so this page cannot silently drift the way a",
        "docstring copy could.",
        "",
        "## Real (constructed today)",
        "",
        "| Kind | Description |",
        "|---|---|",
    ]
    for defn in sorted(
        (d for d in TRANSFORMATION_KINDS.values() if d.status == "real"),
        key=lambda d: d.kind,
    ):
        lines.append(f"| `{defn.kind}` | {defn.description} |")

    lines += [
        "",
        "## Reserved (declared, zero live instances today)",
        "",
        "| Kind | Description |",
        "|---|---|",
    ]
    for defn in sorted(
        (d for d in TRANSFORMATION_KINDS.values() if d.status == "reserved"),
        key=lambda d: d.kind,
    ):
        lines.append(f"| `{defn.kind}` | {defn.description} |")
    lines.append("")
    return "\n".join(lines)
