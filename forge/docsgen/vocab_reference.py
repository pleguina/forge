from pathlib import Path

from forge.ir import build as _ir_build
from forge.topgen.ip.contract_verifier import (
    KNOWN_MEMBERS,
    KNOWN_PROTOCOLS,
    load_canonical_role_vocab,
)

from ._ast_utils import find_call_kwarg_string_values

_IR_BUILD_SOURCE = Path(_ir_build.__file__)


# ── Canonical roles ──────────────────────────────────────────────────────

def generate_canonical_roles_page() -> str:
    vocab = load_canonical_role_vocab()
    lines = [
        "# Canonical Roles",
        "",
        "<!-- Generated by `python -m forge.docsgen`. Do not edit directly. -->",
        "",
        "Generated directly from `forge/topgen/ip/canonical_roles.yaml`",
        "(loaded via",
        "`forge.topgen.ip.contract_verifier.load_canonical_role_vocab()`) —",
        "the canonical *role* vocabulary specifically, distinct from the",
        "[Protocols](protocols.md) and [Interface Members](interface-members.md)",
        "vocabularies, which are separate, independently-validated sources.",
        "See [Contracts and Protocols](../concepts/contracts-and-protocols.md)",
        "for what these roles mean conceptually.",
        "",
        "| Role | Description | Direction | Width | Required | Generation-authoritative | Status |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in sorted(vocab):
        entry = vocab[name] or {}
        description = str(entry.get("description", "")).strip().replace("\n", " ")
        direction = entry.get("direction", "")
        width = entry.get("width", "")
        required = "yes" if entry.get("required") else "no"
        gen_auth = "yes" if entry.get("generation_authoritative") else "no"
        status = entry.get("status", "active")
        lines.append(
            f"| `{name}` | {description} | {direction} | {width} | "
            f"{required} | {gen_auth} | {status} |"
        )
    lines.append("")
    return "\n".join(lines)


